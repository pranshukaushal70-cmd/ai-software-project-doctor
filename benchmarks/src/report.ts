import type { DetectionResult } from "./detection";
import type { Rates } from "./score";

/** Markdown renderings of benchmark results (committed next to the JSON, uploaded by CI). */

export const pct = (x: number | null) => (x === null ? "n/a" : `${(x * 100).toFixed(1)}%`);
const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");
const rateCells = (r: Rates) => `${r.truePositives} | ${r.falsePositives} | ${r.falseNegatives} | ${pct(r.precision)} | ${pct(r.recall)} | ${pct(r.f1)}`;

export function detectionMarkdown(r: DetectionResult): string {
  const out: string[] = [];
  out.push(
    "# Issue-detection benchmark",
    "",
    `Analyzer ${r.analyzerVersion}, OSV.dev ${r.osv}. Generated by \`npm run bench:detection -- --write\`; do not edit by hand.`,
    "Method and caveats: [docs/benchmark.md](../../docs/benchmark.md).",
    "",
    "## Overall",
    "",
    "| TP | FP | FN | Precision | Recall | F1 |",
    "|---:|---:|---:|---:|---:|---:|",
    `| ${rateCells(r.overall)} |`,
    "",
    "## Fixtures",
    "",
    "| Fixture | Labelled categories | Expected | TP | FP | FN | Duplicates | Acceptable | Out of scope | Health |",
    "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|",
  );
  for (const f of r.fixtures) {
    const s = f.score;
    out.push(
      `| ${f.name} | ${f.labeledCategories.join(", ")} | ${f.expected} | ${s.truePositives} | ${s.falsePositives} | ${s.falseNegatives} | ${s.duplicates} | ${s.acceptable} | ${s.outOfScope} | ${f.health.score} (${f.health.grade}) |`,
    );
  }
  out.push("", "## By category", "", "| Category | TP | FP | FN | Precision | Recall | F1 |", "|---|---:|---:|---:|---:|---:|---:|");
  for (const c of r.categories) out.push(`| ${c.category} | ${rateCells(c)} |`);
  out.push("", "## By rule", "", "| Rule | Category | TP | FP | FN | Precision | Recall | F1 |", "|---|---|---:|---:|---:|---:|---:|---:|");
  for (const x of r.rules) out.push(`| \`${x.ruleId}\` | ${x.category ?? ""} | ${rateCells(x)} |`);

  const missed = r.fixtures.flatMap((f) => f.score.missed.map((m) => ({ fixture: f.name, ...m })));
  out.push("", "## Missed issues (false negatives)", "");
  if (!missed.length) out.push("None.");
  else {
    out.push("| Fixture | Rule | Where | Planted issue |", "|---|---|---|---|");
    for (const m of missed) out.push(`| ${m.fixture} | \`${m.ruleId}\` | ${cell(m.path ?? "(repository)")}${m.lines ? `:${m.lines[0]}–${m.lines[1]}` : ""} | ${cell(m.why)} |`);
  }
  const unexpected = r.fixtures.flatMap((f) => f.score.unexpected.map((u) => ({ fixture: f.name, ...u })));
  out.push("", "## Unexpected findings (false positives)", "");
  if (!unexpected.length) out.push("None.");
  else {
    out.push("| Fixture | Rule | Where |", "|---|---|---|");
    for (const u of unexpected) out.push(`| ${u.fixture} | \`${u.ruleId}\` | ${cell(u.path ?? "(repository)")}${u.line ? `:${u.line}` : ""} |`);
  }
  return out.join("\n") + "\n";
}
